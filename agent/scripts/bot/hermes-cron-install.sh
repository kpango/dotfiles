#!/usr/bin/env bash
# hermes-cron-install.sh -- register the pre-check-gated Hermes cron jobs declared in
# agent/harnesses/hermes/cron/jobs.json (called by `make hermes/cron/install`).
#
# Why this shape (Hermes cron docs: hermes-agent.nousresearch.com/docs/user-guide/features/cron):
#   - Hermes stores jobs in ~/.hermes/cron/jobs.json and creates them with `hermes cron create`; they cannot be
#     declared in config.yaml, so the repo keeps a manifest and this script replays it (idempotent, by job name).
#   - A job's pre-run script must be a regular file that resolves inside ~/.hermes/scripts/ (a symlink into the
#     repo is a "symlink escape" and is rejected), so the per-task gates are GENERATED files, not links. The gate
#     runs precheck-cron.sh and ends with {"wakeAgent": false|true}: a quiet tick never starts the LLM (0 tokens).
#   - Cron runs inside the gateway daemon (hermes-gateway.service); without it agent jobs never fire.
#
# usage: hermes-cron-install.sh [--dry-run] [--check]
#   (none)     write the gates, then `hermes cron create` every job that is not listed yet
#   --dry-run  print what would be written / run; touch nothing and never call hermes
#   --check    exit 1 unless every gate is current and every job is listed (read-only)
# env:  HERMES_HOME      default ~/.hermes
#       DOTFILES_ROOT    default: the checkout this script lives in (tests point it at a scratch tree)
set -euo pipefail

die() { printf 'hermes-cron-install: error: %s\n' "$1" >&2; exit 1; }
say() { printf 'hermes-cron-install: %s\n' "$1"; }

dry=0
check=0
for arg in "$@"; do
  case "$arg" in
    --dry-run) dry=1 ;;
    --check) check=1 ;;
    *) printf 'usage: hermes-cron-install.sh [--dry-run] [--check]\n' >&2; exit 2 ;;
  esac
done
[ "$dry" = 1 ] && [ "$check" = 1 ] && die "--dry-run and --check are mutually exclusive"

command -v jq >/dev/null 2>&1 || die "jq not found in PATH"

ROOT="${DOTFILES_ROOT:-$(cd -P "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)}"
ROOT="$(cd -P "$ROOT" && pwd)"
# The root is written into generated scripts, so only plain path characters are accepted.
[[ "$ROOT" =~ ^/[A-Za-z0-9_./+-]+$ ]] || die "dotfiles root '$ROOT' has characters outside [A-Za-z0-9_./+-]; refusing to embed it in a script"
[ -x "$ROOT/agent/scripts/bot/precheck-cron.sh" ] || die "missing or not executable: $ROOT/agent/scripts/bot/precheck-cron.sh"

MANIFEST="$ROOT/agent/harnesses/hermes/cron/jobs.json"
[ -f "$MANIFEST" ] || die "missing manifest: $MANIFEST"

HERMES_HOME="${HERMES_HOME:-$HOME/.hermes}"
[[ "$HERMES_HOME" == /* ]] || die "HERMES_HOME must be an absolute path (got '$HERMES_HOME')"
SCRIPTS="$HERMES_HOME/scripts"

# --- manifest validation (fail closed: nothing is written or created from a bad manifest) ---------------------
jq -e '.jobs | type == "array" and length > 0' "$MANIFEST" >/dev/null 2>&1 || die "manifest .jobs must be a non-empty array"
bad="$(jq -r '
  .jobs[]
  | select(
      (.name | type != "string") or (.name | test("^[a-z0-9][a-z0-9-]{0,63}$") | not)
      or (.task | type != "string") or ([.task] | inside(["pr-review","ci-failure","catalog-drift"]) | not)
      or (.schedule | type != "string") or (.schedule | test("^[ -~]{1,80}$") | not)
      or (.prompt | type != "string") or (.prompt | length < 1) or (.prompt | test("[\u0000-\u0008\u000b-\u001f]"))
    )
  | (.name // "(no name)" | tostring)' "$MANIFEST" 2>/dev/null || echo "(unparseable)")"
[ -z "$bad" ] || die "invalid job(s) in manifest: $(printf '%s' "$bad" | tr '\n' ' ') (need name [a-z0-9-], task pr-review|ci-failure|catalog-drift, printable schedule, non-empty prompt)"
dups="$(jq -r '[.jobs[].name] | group_by(.) | map(select(length > 1) | .[0]) | .[]' "$MANIFEST")"
[ -z "$dups" ] || die "duplicate job name(s) in manifest: $(printf '%s' "$dups" | tr '\n' ' ')"

gate_name() { printf 'dotfiles-precheck-%s.sh' "$1"; }

gate_content() { # gate_content <task>
  cat <<GATE
#!/usr/bin/env bash
# GENERATED by agent/scripts/bot/hermes-cron-install.sh from agent/harnesses/hermes/cron/jobs.json -- do not edit.
# Hermes pre-run gate (0 tokens): the agent wakes only when precheck-cron.sh reports action_required=true.
out="\$('$ROOT/agent/scripts/bot/precheck-cron.sh' --task '$1' --json 2>/dev/null)"
rc=\$?
if [ "\$rc" -eq 0 ] && printf '%s' "\$out" | grep -q '"action_required": *true'; then
  printf '%s\n' "\$out"
  printf '{"wakeAgent": true}\n'
else
  [ "\$rc" -eq 0 ] || echo "precheck $1 could not complete (exit \$rc); not waking the agent" >&2
  printf '{"wakeAgent": false}\n'
fi
GATE
}

tasks="$(jq -r '.jobs[].task' "$MANIFEST" | sort -u)"
rc=0

# --- 1. gates -----------------------------------------------------------------------------------------------
if [ "$check" = 0 ] && [ "$dry" = 0 ]; then
  mkdir -p "$SCRIPTS"
  chmod 0700 "$HERMES_HOME" "$SCRIPTS" 2>/dev/null || true
fi
while IFS= read -r task; do
  [ -n "$task" ] || continue
  g="$SCRIPTS/$(gate_name "$task")"
  want="$(gate_content "$task")"
  if [ "$check" = 1 ]; then
    if [ -f "$g" ] && [ ! -L "$g" ] && [ "$(cat "$g")" = "$want" ] && [ -x "$g" ]; then
      say "gate ok: $g"
    else
      say "gate MISSING or stale (or a symlink): $g"
      rc=1
    fi
  elif [ "$dry" = 1 ]; then
    say "would write gate $g (0700, regular file)"
  else
    tmp="$(mktemp "$SCRIPTS/.gate.XXXXXX")"
    printf '%s\n' "$want" >"$tmp"
    chmod 0700 "$tmp"
    mv -f "$tmp" "$g" # rename replaces a pre-existing file or symlink instead of writing through it
    say "wrote gate $g"
  fi
done <<<"$tasks"

# --- 2. jobs ------------------------------------------------------------------------------------------------
listed=""
if [ "$dry" = 0 ]; then
  command -v hermes >/dev/null 2>&1 || die "hermes not found in PATH (install Hermes first; use --dry-run to preview)"
  listed="$(hermes cron list 2>&1)" || die "'hermes cron list' failed: $(printf '%s' "$listed" | head -c 200)"
fi

n_jobs="$(jq '.jobs | length' "$MANIFEST")"
for ((i = 0; i < n_jobs; i++)); do
  name="$(jq -r ".jobs[$i].name" "$MANIFEST")"
  schedule="$(jq -r ".jobs[$i].schedule" "$MANIFEST")"
  task="$(jq -r ".jobs[$i].task" "$MANIFEST")"
  prompt="$(jq -r ".jobs[$i].prompt" "$MANIFEST")"
  gate="$(gate_name "$task")"
  if [ "$dry" = 1 ]; then
    say "would run: hermes cron create '$schedule' <prompt: ${#prompt} chars> --name $name --script $gate --deliver local"
    continue
  fi
  # `name` is [a-z0-9-] (validated above), so it is safe inside a regex; the boundary stops 'x' matching 'x-2'.
  if printf '%s\n' "$listed" | grep -Eq "(^|[^A-Za-z0-9-])${name}([^A-Za-z0-9-]|\$)"; then
    say "job exists: $name"
    continue
  fi
  if [ "$check" = 1 ]; then
    say "job MISSING: $name"
    rc=1
    continue
  fi
  hermes cron create "$schedule" "$prompt" --name "$name" --script "$gate" --deliver local
  say "created job: $name ($schedule, gate $gate)"
done

if [ "$rc" -ne 0 ]; then
  say "check failed: run 'make hermes/cron/install'"
  exit "$rc"
fi
[ "$check" = 1 ] && say "all gates current and all jobs listed"
[ "$dry" = 0 ] && [ "$check" = 0 ] && say "done (cron runs inside the gateway daemon: systemctl --user status hermes-gateway.service)"
exit 0
