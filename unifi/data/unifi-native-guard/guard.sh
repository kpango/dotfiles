#!/bin/bash
#
# unifi-native-guard — keep Ubiquiti-built packages intact while the rest of the
# system follows the latest Debian trixie packages (called from /root/update.sh).
#
#   guard.sh pins      write apt pins that forbid Debian's builds of Ubiquiti packages
#   guard.sh preflight abort (rc=1) if an apt dist-upgrade would replace/remove them
#   guard.sh verify    restore any replaced package from the firmware layer, then run
#                      functional checks of the userspace pieces udapi-server needs
#   guard.sh units     (re)install the eth8 Region Blocking units (lost on firmware update)
#
# Background: on 2026-09-21 `apt dist-upgrade` replaced Ubiquiti's iptables/libxtables
# (dpi*/dyn_random/geoip extensions), frr (/usr/sbin/zebra), dnsmasq etc. with Debian
# builds; every config apply of ubios-udapi-server then failed and rolled back
# ("Gateway Configuration Failed", no IPv4 WAN steering, default-open firewall).
#
set -uo pipefail
G=/data/unifi-native-guard
ROFS=/mnt/.rofs
ADM=$ROFS/var/lib/dpkg
PIN=/etc/apt/preferences.d/30-unifi-native-protect
# Debian packages that would push out a protected package (Breaks/Replaces)
BLOCK_EXTRA="libyang3 miniupnpd-nftables miniupnpd-iptables"

firmware_version() { dpkg-query --admindir=$ADM -W -f='${Version}' "$1" 2>/dev/null; }

# Ubiquiti-built (or Ubiquiti-held) packages of the running firmware that are installed
protected() {
    dpkg-query --admindir=$ADM -W -f='${Package} ${Version} ${Maintainer}\n' |
        awk '$2 ~ /ubnt|\+ui|-[0-9]+\+g[0-9a-f]{12}|deb11|bpo11/ || $0 ~ /[Uu]biquiti/ {print $1}' |
        while read -r p; do dpkg-query -W -f='${Package}\n' "$p" >/dev/null 2>&1 || [ "$(firmware_version "$p")" ] && echo "$p"; done
}

# Subset that Debian also ships (only those can be clobbered by apt)
colliding() {
    for p in $(protected); do
        case "$p" in libiptc0|libyang2) echo "$p"; continue ;; esac
        apt-cache madison "$p" 2>/dev/null | grep 'debian\.org' >/dev/null && echo "$p"
    done
}

cmd_pins() {
    local list
    list=$(colliding | sort -u | tr '\n' ' ')
    {
        echo "# Generated by $G/guard.sh on $(date -Iseconds). Do not edit."
        echo "# Debian builds of these Ubiquiti packages break ubios-udapi-server."
        for o in deb.debian.org security.debian.org; do
            echo; echo "Package: $list $BLOCK_EXTRA"
            echo "Pin: origin $o"
            echo "Pin-Priority: -10"
        done
    } > "$PIN.tmp" && mv "$PIN.tmp" "$PIN"
    # superseded hand-written pin (it froze whatever version was installed, even broken ones)
    rm -f /etc/apt/preferences.d/20-network-stack-protect
    echo "apt pins written: $PIN ($(echo $list | wc -w) packages)"
}

cmd_preflight() {
    local sim bad
    sim=$(apt-get -s dist-upgrade 2>&1)
    bad=$(for p in $(protected) $BLOCK_EXTRA; do
        echo "$sim" | grep -E "^(Inst|Remv) $p[ :]" ; done)
    if [ -n "$bad" ]; then
        echo "ERROR: dist-upgrade would replace/remove Ubiquiti packages:" >&2
        echo "$bad" >&2
        return 1
    fi
    echo "preflight: dist-upgrade does not touch Ubiquiti packages."
}

cmd_verify() {
    local mism=() p fw cur rc=0
    for p in $(protected); do
        fw=$(firmware_version "$p"); cur=$(dpkg-query -W -f='${Version}' "$p" 2>/dev/null)
        # newer Ubiquiti builds (e.g. unifi-core updates from UniFi OS) are fine
        if [ "$cur" != "$fw" ] && ! echo "$cur" | grep -qE 'ubnt|\+ui|-[0-9]+\+g[0-9a-f]{12}' \
            && ! dpkg-query -W -f='${Maintainer}' "$p" 2>/dev/null | grep -qi ubiquiti; then
            mism+=("$p")
        fi
    done
    for p in $BLOCK_EXTRA; do
        dpkg-query -W -f='${Status}' "$p" 2>/dev/null | grep -q 'ok installed' &&
            { echo "removing conflicting Debian package $p"; dpkg --purge --force-depends "$p"; }
    done
    if [ ${#mism[@]} -gt 0 ]; then
        echo "WARNING: Debian builds replaced Ubiquiti packages: ${mism[*]}"
        local out; out=$(mktemp -d)
        OUT=$out "$G/repack-from-rofs.sh" "${mism[@]}" &&
            DEBIAN_FRONTEND=noninteractive dpkg -i --force-confnew "$out"/*.deb &&
            echo "restored from firmware layer: ${mism[*]}" || rc=1
        rm -rf "$out"
        echo "ACTION: run 'systemctl restart udapi-server' so the gateway config is re-applied."
    fi
    # functional checks of what udapi-server needs
    iptables -m dyn_random -h >/dev/null 2>&1 || { echo "FAIL: iptables dyn_random extension"; rc=1; }
    iptables -m geoip -h     >/dev/null 2>&1 || { echo "FAIL: iptables geoip extension"; rc=1; }
    iptables -m dpi128 -h    >/dev/null 2>&1 || { echo "FAIL: iptables dpi128 extension"; rc=1; }
    [ -x /usr/sbin/zebra ]                    || { echo "FAIL: /usr/sbin/zebra missing"; rc=1; }
    [ $rc = 0 ] && echo "verify: Ubiquiti packages and iptables extensions OK."
    return $rc
}

# systemd units live in the rootfs overlay, which a firmware update resets
cmd_units() {
    local u changed=0
    for u in "$G"/units/*; do
        cmp -s "$u" "/etc/systemd/system/$(basename "$u")" || { cp "$u" /etc/systemd/system/; changed=1; }
    done
    [ $changed = 1 ] && systemctl daemon-reload
    systemctl enable --now unifi-native-guard-geoip-eth8.timer unifi-native-guard-geoip-eth8.path >/dev/null 2>&1
    systemctl is-active --quiet unifi-native-guard-geoip-eth8.timer &&
        echo "units: eth8 Region Blocking guard active." || { echo "FAIL: eth8 Region Blocking guard"; return 1; }
}

case "${1:-}" in
    pins) cmd_pins ;; preflight) cmd_preflight ;; verify) cmd_verify ;; units) cmd_units ;;
    *) echo "usage: $0 pins|preflight|verify|units" >&2; exit 2 ;;
esac
